"""
Test Login with Shop Credentials

This script tests if a shop owner can login with the credentials 
generated by create_shop_from_lead.

Usage:
    python test_shop_login.py
"""

from app.database import SessionLocal
from app.models.user import User
from app.models.shop import Shop
from app.utils.security import verify_password, create_access_token

db = SessionLocal()

print("🔐 Testing Shop Owner Login\n")
print("=" * 60)

# Get the most recently created shop with credentials
shop = db.query(Shop).filter(
    Shop.temporary_password.isnot(None)
).order_by(Shop.created_at.desc()).first()

if not shop:
    print("\n❌ No shops with credentials found!")
    print("\n💡 You need to:")
    print("   1. Create a shop from a lead in Kitchen dashboard")
    print("   2. Or run: python create_test_shop.py")
    db.close()
    exit(1)

# Get the owner
owner = db.query(User).filter(User.id == shop.owner_id).first()

print(f"\n🏪 Shop: {shop.name} ({shop.subdomain}.1line.az)")
print(f"👤 Owner: {owner.full_name}")
print(f"📧 Email: {owner.email}")
print(f"🔑 Temp Password: {shop.temporary_password}")
print(f"✅ Active: {owner.is_active}")
print(f"👑 Superuser: {owner.is_superuser}")

# Test password verification
print(f"\n🔐 Testing password verification...")
is_valid = verify_password(shop.temporary_password, owner.hashed_password)
print(f"   Password matches hash: {'✅ YES' if is_valid else '❌ NO'}")

if not is_valid:
    print(f"\n❌ PASSWORD VERIFICATION FAILED!")
    print(f"\nPossible issues:")
    print(f"   1. Password was changed after creation")
    print(f"   2. Hash wasn't generated correctly")
    print(f"   3. Database wasn't committed properly")
    db.close()
    exit(1)

# Test token generation
print(f"\n🎫 Testing JWT token generation...")
try:
    token = create_access_token(data={"sub": owner.email})
    print(f"   Token generated: {token[:50]}...")
    print(f"   ✅ Token generation successful")
except Exception as e:
    print(f"   ❌ Token generation failed: {e}")
    db.close()
    exit(1)

# Simulate login
print(f"\n🚪 Simulating login...")
if not owner.is_active:
    print(f"   ❌ User is not active!")
else:
    print(f"   ✅ User is active")
    print(f"   ✅ Login would succeed!")
    print(f"\n📝 Login credentials:")
    print(f"   Email: {owner.email}")
    print(f"   Password: {shop.temporary_password}")
    print(f"\n🌐 Login URL: http://localhost:5173/login")

print("\n" + "=" * 60)
print("✅ All tests passed! Login should work.\n")

db.close()
